  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  // 生成 10 条：保证各分类均衡（按当前 POOL 实际分类动态轮转）
  function generate(force) {
    const today = Store.todayStr();
    if (!force && Store.DB.viral.date === today && Store.DB.viral.items.length) {
      return Store.DB.viral.items;
    }
    const cats = Array.from(new Set(POOL.map((p) => p.category)));
    const byCat = {};
    cats.forEach((c) => (byCat[c] = shuffle(POOL.filter((p) => p.category === c))));
    const picked = [];
    // 轮流取，保证均衡
    let round = 0;
    while (picked.length < 10) {
      const c = cats[round % cats.length];
      const item = byCat[c].shift();
      if (item) picked.push(item);
      else {
        // 该类用完，从剩余补
        const rest = shuffle(POOL).find((p) => !picked.includes(p));
        if (rest) picked.push(rest); else break;
      }
      round++;
    }
    Store.DB.viral = { date: today, items: picked };
    Store.save();
    return picked;
  }

